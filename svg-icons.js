// Helper function to get icon HTML
function getIcon(name, size = 'normal') {
    const icon = SVG_ICONS[name] || SVG_ICONS.player;
    const sizeClass = size === 'large' ? 'svg-icon-xl' : size === 'small' ? 'svg-icon' : 'svg-icon-lg';
    return `<span class="svg-icon ${sizeClass}">${icon}</span>`;
}

// Auto-replace emojis with SVG icons in a container
function replaceEmojisWithIcons(container) {
    const emojiMap = {
        '🧑': 'player',
        '🦅': 'horus',
        '🐺': 'set',
        '💀': 'anubis',
        '🪙': 'gold',
        '🩸': 'goldenBlood',
        '🌾': 'wheat',
        '⛏️': 'mining',
        '🏛️': 'obelisk',
        '👑': 'palace',
        '⚔️': 'attack',
        '☀️': 'sun',
        '🔨': 'craft',
        '🎒': 'inventory',
        '📜': 'quests',
        '⚡': 'lightning',
        '✨': 'sparkle',
        '🔊': 'audio',
        '🗺️': 'map',
        '💬': 'chat',
        '✕': 'close',
        '✅': 'check',
        '❌': 'cross',
        '👁️': 'eye',
        '↗': 'external',
        '▶': 'arrowRight',
        '⚖️': 'scale',
        '⏱️': 'clock'
    };
    
    const walker = document.createTreeWalker(
        container,
        NodeFilter.SHOW_TEXT,
        null,
        false
    );
    
    const textNodes = [];
    let node;
    while (node = walker.nextNode()) {
        textNodes.push(node);
    }
    
    textNodes.forEach(textNode => {
        let text = textNode.textContent;
        let modified = false;
        
        for (const [emoji, iconName] of Object.entries(emojiMap)) {
            if (text.includes(emoji)) {
                text = text.replace(emoji, `__SVG_ICON_${iconName}__`);
                modified = true;
            }
        }
        
        if (modified) {
            const fragment = document.createDocumentFragment();
            const parts = text.split(/__SVG_ICON_(\w+)__/);
            
            parts.forEach((part, index) => {
                if (index % 2 === 0) {
                    if (part) {
                        fragment.appendChild(document.createTextNode(part));
                    }
                } else {
                    const span = document.createElement('span');
                    span.innerHTML = getIcon(part);
                    span.className = 'inline-flex items-center';
                    fragment.appendChild(span);
                }
            });
            
            textNode.parentNode.replaceChild(fragment, textNode);
        }
    });
}

